def ollama_services():
    base = {
        "image": OLLAMA,
        "restart": "unless-stopped",
        "environment": ["OLLAMA_CONTEXT_LENGTH=8192", "OLLAMA_FLASH_ATTENTION=1",
                        "OLLAMA_KV_CACHE_TYPE=q8_0", "OLLAMA_MAX_LOADED_MODELS=2"],
        "volumes": ["ollama_storage:/root/.ollama"],
        "aliases": ["ollama"],
    }
    gpu = {"resources": {"reservations": {"devices": [
        {"driver": "nvidia", "count": 1, "capabilities": ["gpu"]}]}}}
    # Waits up to two minutes for Ollama, pulls the models, exits 0. With no
    # Ollama running (OLLAMA_CPU_REPLICAS=0 and no GPU profile) it skips.
    pulls = " && ".join(f"ollama pull {m}" for m in MODELS)
    pull = (f'timeout 120 sh -c "until ollama list >/dev/null 2>&1; do sleep 2; done" '
            f'|| {{ echo "no ollama, skipping model pull"; exit 0; }}; {pulls}')
    return {
        "ollama-cpu": {**base, "deploy": {"replicas": "${OLLAMA_CPU_REPLICAS}"}},
        "ollama-gpu": {**base, "profiles": ["gpu-nvidia"], "deploy": gpu},
        "ollama-gpu-amd": {**base, "profiles": ["gpu-amd"], "image": OLLAMA_ROCM,
                           "devices": ["/dev/kfd", "/dev/dri"]},
        "ollama-pull": {
            "image": OLLAMA,
            "restart": "no",
            "environment": ["OLLAMA_HOST=ollama:11434"],
            "entrypoint": "/bin/sh",
            "command": ["-c", pull],
        },
    }


