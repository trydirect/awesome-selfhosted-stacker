def fetch(repo, commit, dest, sparse=None):
    run = lambda *a: subprocess.run(a, cwd=dest, check=True, capture_output=True)
    dest.mkdir(parents=True)
    run("git", "init", "-q")
    run("git", "remote", "add", "origin", repo)
    if sparse:
        run("git", "sparse-checkout", "set", sparse)
    run("git", "fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", commit)
    run("git", "checkout", "-q", "FETCH_HEAD")
    return dest


