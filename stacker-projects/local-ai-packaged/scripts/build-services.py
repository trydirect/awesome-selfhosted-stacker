DEFAULTED = re.compile(r"\$\{(\w+)(:?[-?])([^}]*)\}")
PLAIN = re.compile(r"\$\{(\w+)\}")


def resolve(value, keys):
    """`${K:-d}` -> `${K}` when K is a stack key, else `d`. None when the
    result is empty (an unset optional setting is left out)."""
    value = str(value)
    value = DEFAULTED.sub(lambda m: f"${{{m.group(1)}}}" if m.group(1) in keys else m.group(3), value)
    for name in PLAIN.findall(value):
        if name not in keys:
            sys.exit(f"`${{{name}}}` is not in .env.example")
    return value


def env_map(env, keys):
    if isinstance(env, list):
        env = dict(e.split("=", 1) for e in env)
    out = {}
    for key, value in (env or {}).items():
        value = resolve("" if value is None else value, keys)
        if value != "":
            out[key] = value
    return out


def command_string(cmd):
    return cmd if isinstance(cmd, str) else shlex.join(str(c) for c in cmd)


def healthcheck(hc):
    test = hc["test"]
    if isinstance(test, list):
        kind, args = test[0], [str(a) for a in test[1:]]
        if kind == "CMD-SHELL":
            test = "CMD-SHELL " + " ".join(args)
        elif any(re.search(r"[\s&|;$<>()'\"]", a) for a in args):
            test = "CMD-SHELL " + shlex.join(args)
        else:
            test = "CMD " + " ".join(args)
    out = {"test": test}
    seconds = lambda d: int(re.match(r"(\d+)", str(d)).group(1)) * (60 if str(d).endswith("m") else 1)
    interval = hc.get("interval", "30s")
    retries = int(hc.get("retries", 3))
    if hc.get("start_period"):
        # No start_period in stacker.yml: give the same grace through retries.
        retries += -(-seconds(hc["start_period"]) // max(seconds(interval), 1))
    out.update({"interval": interval, "timeout": hc.get("timeout", "30s"), "retries": retries})
    return out


def to_stacker(name, svc, keys):
    unknown = set(svc) - DROPPED - {
        "image", "environment", "volumes", "ports", "depends_on", "command", "entrypoint",
        "healthcheck", "restart", "cap_add", "cap_drop", "devices", "profiles", "deploy",
        "networks", "aliases"}
    if unknown:
        sys.exit(f"{name}: compose keys with no stacker.yml field: {sorted(unknown)}")
    out = {"name": name, "image": svc["image"]}
    if svc.get("ports"):
        out["ports"] = [str(p) for p in svc["ports"]]
    env = env_map(svc.get("environment"), keys)
    if env:
        out["environment"] = env
    if svc.get("volumes"):
        out["volumes"] = svc["volumes"]
    deps = svc.get("depends_on")
    if deps:
        out["depends_on"] = list(deps)  # conditions have no stacker.yml field
    for key in ("command", "entrypoint"):
        if svc.get(key):
            out[key] = resolve(command_string(svc[key]), keys)
    if svc.get("healthcheck"):
        out["healthcheck"] = healthcheck(svc["healthcheck"])
    if svc.get("restart"):
        out["restart"] = svc["restart"]
    for key in ("cap_add", "cap_drop", "devices", "profiles"):
        if svc.get(key):
            out[key] = svc[key]
    aliases = list(svc.get("aliases", []))
    for net in (svc.get("networks") or {}).values() if isinstance(svc.get("networks"), dict) else []:
        aliases += (net or {}).get("aliases", [])
    if aliases:
        out["aliases"] = aliases
    if svc.get("deploy"):
        out["deploy"] = svc["deploy"]
    return out


