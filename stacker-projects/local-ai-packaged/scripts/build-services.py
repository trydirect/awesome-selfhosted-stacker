def supabase_files(src, services):
    files = {}
    for svc in services.values():
        for v in svc.get("volumes", []):
            host = v.split(":")[0]
            if host.startswith("./supabase/volumes/"):
                rel = host[len("./supabase/"):]
                files[f"supabase/{rel}"] = (src / "docker" / rel).read_bytes()
    return files


def searxng_settings(src):
    settings = load(src / "searxng/settings-base.yml")
    settings["server"].pop("secret_key", None)  # SEARXNG_SECRET sets it per machine
    settings.pop("redis", None)  # the limiter is off; Redis here needs a password
    return ("# Built by scripts/build-services.py from local-ai-packaged searxng/settings-base.yml\n"
            + yaml.safe_dump(settings, sort_keys=False)).encode()


def build():
    keys = env_keys()
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        local_ai = fetch(*LOCAL_AI, tmp / "local-ai")
        supabase = fetch(*SUPABASE, tmp / "supabase", sparse="docker")
        langfuse = fetch(*LANGFUSE, tmp / "langfuse")

        services = local_ai_services(local_ai)
        services.update(ollama_services())
        services.update(langfuse_services(langfuse))
        sb = supabase_services(supabase)
        clash = set(services) & set(sb)
        if clash:
            sys.exit(f"service names used twice: {sorted(clash)}")
        services.update(sb)
        for old, new in RENAMED.items():
            svc = services.pop(old)
            svc["aliases"] = [old] + list(svc.get("aliases", []))
            services[new] = svc
        for svc in services.values():
            if svc.get("depends_on"):
                deps = svc["depends_on"]
                deps = list(deps) if isinstance(deps, (list, dict)) else [deps]
                svc["depends_on"] = [RENAMED.get(d, d) for d in deps]

        files = supabase_files(supabase, services)
        files["Caddyfile"] = (local_ai / "Caddyfile").read_bytes().replace(
            b"import /etc/caddy/addons/*.conf\n", b"")
        files["searxng/settings.yml"] = searxng_settings(local_ai)

    stacker_services = [secrets_through_environment(to_stacker(name, svc, keys))
                        for name, svc in services.items()]
    secrets_outside_environment(stacker_services)
    one_reference_per_name(stacker_services)
    volumes = sorted({v.split(":")[0] for s in stacker_services for v in s.get("volumes", [])
                      if not v.startswith((".", "/"))})
    block = yaml.dump({"services": stacker_services, "volumes": {v: {} for v in volumes},
                       "config_contract": contract(stacker_services)},
                      Dumper=NoAliasDumper, sort_keys=False, width=1000, allow_unicode=True)
    header = (f"# local-ai-packaged {LOCAL_AI[1][:12]}, supabase {SUPABASE[1][:12]}, "
              f"langfuse {LANGFUSE[1][:12]}\n")
    return header + block, files, len(stacker_services), len(volumes)


class NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def is_secret(key):
    k = key.lower()
    return "password" in k or "secret" in k or "_key" in k or "token" in k


def contract(services):
    """Policies per service for every secret-shaped name it reads. A name whose
    value is `${KEY}` for a stack key gets KEY's policy if it is KEY itself,
    and a plain generated one otherwise: the compose reads ${KEY}, so the extra
    value is never used - it only answers the publish check."""
    out = {}
    unreferenced = []
    for svc in services:
        fields = {}
        for name, value in svc.get("environment", {}).items():
            ref = PLAIN.fullmatch(value)
            if ref and ref.group(1) in POLICIES:
                if name == ref.group(1):
                    fields[name] = POLICIES[name]
                elif is_secret(name):
                    fields[name] = POLICIES[ref.group(1)] if POLICIES[ref.group(1)] is OPTIONAL else ALNUM
            elif is_secret(name):
                unreferenced.append(f"{svc['name']}.{name}={value}")
        # Every stack key needs a policy somewhere, even one no env name repeats.
        if fields:
            out.setdefault(svc["name"], {})["fields"] = fields
        if svc["name"] in KEPT_VOLUMES:
            out.setdefault(svc["name"], {})["volumes"] = {
                v: {"mutability": "fixed"} for v in KEPT_VOLUMES[svc["name"]]}
    if unreferenced:
        sys.exit("secret-shaped but not a ${KEY} reference:\n  " + "\n  ".join(unreferenced))
    # A stack key read only under another name or inside a larger value
    # (SALT: ${LANGFUSE_SALT}, NEO4J_AUTH: neo4j/${NEO4J_PASSWORD}) is declared
    # on the first service that references it, so a clone regenerates it.
    declared = {k for s in out.values() for k in s.get("fields", {})}
    for key in sorted(set(POLICIES) - declared):
        reader = next((svc["name"] for svc in services
                       if any(key in PLAIN.findall(v) for v in svc.get("environment", {}).values())), None)
        if reader is None:
            sys.exit(f"stack key no service reads: {key}")
        out.setdefault(reader, {}).setdefault("fields", {})[key] = POLICIES[key]
    # derived_jwt signs with JWT_SECRET where that key is declared itself.
    signer = next(name for name, s in out.items()
                  if s.get("fields", {}).get("JWT_SECRET", {}).get("type") == "alphanumeric"
                  and s["fields"]["JWT_SECRET"].get("min_length") == 40)
    out = copy.deepcopy(out)
    for s in out.values():
        for policy in s.get("fields", {}).values():
            if policy.get("type") == "derived_jwt":
                policy["signing_key"] = f"{signer}.JWT_SECRET"
    return {"services": out}


def secrets_through_environment(svc):
    """A healthcheck or command that names a secret as ${KEY} reads it from the
    container's environment instead ($$KEY), with KEY added to `environment`:
    a bake turns secrets into references inside environment blocks only."""
    for key in ("command", "entrypoint", "healthcheck"):
        if key not in svc:
            continue
        text = yaml.safe_dump(svc[key])
        names = [n for n in PLAIN.findall(text) if n in POLICIES]
        for name in names:
            text = text.replace(f"${{{name}}}", f"$${name}")
            svc.setdefault("environment", {})[name] = f"${{{name}}}"
        if names:
            svc[key] = yaml.safe_load(text)
    return svc


def one_reference_per_name(services):
    """stacker restores `${VAR}` references by env name for the whole file, so
    an env name must reference the same key in every service (see BUGS.md)."""
    seen = {}
    for svc in services:
        for name, value in svc.get("environment", {}).items():
            ref = PLAIN.fullmatch(value)
            if ref:
                seen.setdefault(name, {}).setdefault(ref.group(1), []).append(svc["name"])
    clashes = {n: refs for n, refs in seen.items() if len(refs) > 1}
    if clashes:
        sys.exit("env names referencing different keys across services: " + str(clashes))


def secrets_outside_environment(services):
    """A ${KEY} for a secret outside `environment` would stay literal in a
    baked image: the bake parameterizes environment blocks only."""
    bad = []
    for svc in services:
        for key in ("command", "entrypoint", "healthcheck"):
            text = yaml.safe_dump(svc.get(key, ""))
            for name in PLAIN.findall(text):
                if name in POLICIES:
                    bad.append(f"{svc['name']}.{key}: ${{{name}}}")
    if bad:
        sys.exit("secrets outside environment: " + ", ".join(bad))


def splice(stacker_yml, block):
    start, end = stacker_yml.index(BEGIN), stacker_yml.index(END)
    return stacker_yml[: start + len(BEGIN)] + "\n" + block + stacker_yml[end:]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if stacker.yml or the files differ from a fresh build")
    check = parser.parse_args().check

    block, files, n_services, n_volumes = build()
    current = (STACK / "stacker.yml").read_text()
    wanted = splice(current, block)
    drift = [] if wanted == current else ["stacker.yml"]
    for rel, data in files.items():
        path = STACK / rel
        if not path.exists() or path.read_bytes() != data:
            drift.append(rel)

    if check:
        if drift:
            sys.exit("out of date, run scripts/build-services.py: " + ", ".join(drift))
        print("up to date")
        return
    shutil.rmtree(STACK / "supabase" / "volumes", ignore_errors=True)
    for rel, data in files.items():
        (STACK / rel).parent.mkdir(parents=True, exist_ok=True)
        (STACK / rel).write_bytes(data)
    (STACK / "stacker.yml").write_text(wanted)
    print(f"stacker.yml: {n_services} services, {n_volumes} volumes")


if __name__ == "__main__":
    main()
