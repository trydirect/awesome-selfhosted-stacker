#!/usr/bin/env python3
"""Build the `services:` and `volumes:` of stacker.yml from the upstream stack.

  uv run --with pyyaml python3 scripts/build-services.py          # rewrite
  uv run --with pyyaml python3 scripts/build-services.py --check  # CI: fail on drift

The stack is coleam00/local-ai-packaged: its own services, plus Supabase's
self-hosting compose (which upstream pulls in with `include:` from an unpinned
clone of supabase master) and Langfuse. Each source is fetched at a pinned
commit and turned into stacker.yml services, changed only where a reproducible
stacker deploy needs it:

  - every image pinned to a version (upstream uses `latest` for most);
  - Langfuse taken from Langfuse's own compose: upstream still points at
    minio/minio, which is no longer published;
  - directory bind mounts become named volumes, or mounts of the single files
    the service reads (`stacker deploy` uploads files, not directories);
  - no service publishes a port except Caddy, which serves every UI;
  - `${KEY:-default}` (which stacker.yml does not accept) becomes `${KEY}` when
    KEY is in .env.example and the default otherwise; a credential never keeps
    an insecure default;
  - Ollama: the CPU variant runs unless OLLAMA_CPU_REPLICAS=0, the GPU variants
    only under the upstream profiles; all of them answer as `ollama`.

Only the block between the markers in stacker.yml is written; everything else
in stacker.yml (deploy, config_contract, hooks) is edited by hand. Also writes
Caddyfile, searxng/settings.yml and supabase/volumes/.
"""

